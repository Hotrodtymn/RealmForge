#!/bin/zsh
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd -P)"
PROJECT_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd -P)"
ICON_OUTPUT_DIR="$SCRIPT_DIR/icons"
[[ -f "$ICON_OUTPUT_DIR/RealmForge.icns" && -f "$ICON_OUTPUT_DIR/RealmForgeStop.icns" ]] || {
	print -u2 "Custom RealmForge icon files are missing under $ICON_OUTPUT_DIR."
	exit 1
}

build_bundle() {
	local source_file="$1"
	local output_path="$2"
	local bundle_id="$3"
	local display_name="$4"
	local icon_name="$5"
	local resources_path="$output_path/Contents/Resources"

	if [[ -e "$output_path" ]]; then
		if [[ ! -f "$output_path/Contents/Resources/RealmForgeLauncherBuild" ]]; then
			print -u2 "Refusing to replace unrecognized app bundle: $output_path"
			return 1
		fi
		rm -rf "$output_path"
	fi

	osacompile -l JavaScript -o "$output_path" "$SCRIPT_DIR/$source_file"
	print -r -- "RealmForge launcher bundle; generated by launcher/macos/build-app.sh" > "$output_path/Contents/Resources/RealmForgeLauncherBuild"
	mkdir -p "$resources_path/launcher/macos"
	install -m 755 "$SCRIPT_DIR/realmforge.sh" "$resources_path/launcher/macos/realmforge.sh"
	install -m 644 "$SCRIPT_DIR/realmforge.cjs" "$resources_path/launcher/macos/realmforge.cjs"
	print -r -- "$PROJECT_ROOT" > "$resources_path/RealmForgeProjectRoot"
	cp "$ICON_OUTPUT_DIR/$icon_name.icns" "$resources_path/$icon_name.icns"
	/usr/libexec/PlistBuddy -c "Add :CFBundleIdentifier string $bundle_id" "$output_path/Contents/Info.plist"
	/usr/libexec/PlistBuddy -c "Set :CFBundleName $display_name" "$output_path/Contents/Info.plist"
	/usr/libexec/PlistBuddy -c "Set :CFBundleIconFile $icon_name" "$output_path/Contents/Info.plist"
	/usr/libexec/PlistBuddy -c "Set :CFBundleIconName $icon_name" "$output_path/Contents/Info.plist"
	/usr/libexec/PlistBuddy -c "Add :NSDocumentsFolderUsageDescription string RealmForge needs access to its project files in Documents to run the campaign server." "$output_path/Contents/Info.plist"
}

build_bundle RealmForge.js "$PROJECT_ROOT/RealmForge.app" com.realmforge.launcher RealmForge RealmForge
build_bundle RealmForge-Stop.js "$PROJECT_ROOT/RealmForge Stop.app" com.realmforge.stop RealmForgeStop RealmForgeStop
print "Built RealmForge.app and RealmForge Stop.app in $PROJECT_ROOT"
